class Font:
    """Proportional bitmap font. glyph(ch) -> bool array (rows, width)."""

    def __init__(self, table, cap, spacing=1, fallback='?'):
        self.cap = cap          # cap height in px (rows of an uppercase glyph)
        self.spacing = spacing  # px between glyphs
        self.glyphs = {}
        for ch, rows in table.items():
            w = max(len(r) for r in rows)
            a = np.zeros((len(rows), w), bool)
            for y, r in enumerate(rows):
                for x, c in enumerate(r):
                    a[y, x] = c == '#'
            self.glyphs[ch] = a
        self.fallback = fallback
        # descender cell height (tallest glyph)
        self.height = max(g.shape[0] for g in self.glyphs.values())

    def has(self, ch):
        return ch in self.glyphs or (ch.upper() != ch and ch.upper() in self.glyphs)

    def missing(self, s):
        """Characters of s this font cannot draw (they would render as the fallback '?')."""
        return sorted({c for c in s if not self.has(c)})

    def glyph(self, ch):
        g = self.glyphs.get(ch)
        if g is None:
            g = self.glyphs.get(ch.upper()) if ch.upper() != ch else None
        if g is None:
            MISSING.add(ch)
            g = self.glyphs.get(self.fallback)
        return g

    def width(self, s):
        if not s:
            return 0
        return sum(self.glyph(c).shape[1] for c in s) + self.spacing * (len(s) - 1)


